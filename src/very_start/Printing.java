package very_start;

public class Printing {
	public static void main(String[] args) {

		// Use print or println

		System.out.print("Print test in one line.\n");
		System.out.print("Print    test in one line. \n");
		
		System.out.println("Print this in one line with no escape chars.");
		
		// Using tab escape char
		System.out.println("\t Texto após um tab.");
	}
	

}
